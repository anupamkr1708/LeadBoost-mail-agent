"""
Migration 013: external_dispatches content-approval columns (managed-reply exact-content approval).

Adds the evidence a LeadBoost-managed reply needs so that the text a user approved is provably the text that
is sent (see mailer_agent/mail/content_digest.py and api/integrations_reply_drafts.py):

external_dispatches:
  + content_approval_required  BOOLEAN NOT NULL DEFAULT FALSE
      TRUE: the generated subject/body must be released by digest before the SMTP worker may send it.
      Every existing row gets FALSE, so ordinary and already-processed dispatches behave exactly as before.
  + approved_content_sha256    VARCHAR(64) NULL    digest recorded by the release; written once
  + approved_at                TIMESTAMP (tz) NULL when the release was recorded

No new table, no index (every lookup is by the existing UNIQUE(organization_id, idempotency_key)), no
backfill. ``state`` is a plain string column with no CHECK constraint, so the new internal states
('awaiting_approval', 'cancelled') need no DDL.

Apply BEFORE deploying the code that includes this change: the ORM selects these columns on every
ExternalDispatch query, so new code against an un-migrated database fails on the first dispatch read.
Older code ignores the extra columns, so rolling the CODE back does not require the downgrade.

ROLLOUT PRECONDITION -- enforced, not merely documented: ``python scripts/migrate_preflight.py gate`` (which the
release wrapper runs before any migration, and which is read-only without --apply) REFUSES with exit 4 while ANY
unresolved LEGACY managed-reply dispatch exists: one with a reply_parent in grounding_context and
content_approval_required not set, in state queued (with OR without a generated message), generating, or sending.
Queued/generating-with-message rows would send text nobody reviewed. Queued-WITHOUT-message rows would be generated by
the new worker into AWAITING_APPROVAL, where LeadBoost's new UI -- which treats the old action as legacy -- can neither
review nor release them: a stranded draft. ``grounding_context`` is a JSON column, so the predicate is a JSON-key test,
not LIKE (PostgreSQL has no ``json ~~ text`` operator):

    SELECT state, (message_id IS NOT NULL) AS has_message, count(*)
      FROM external_dispatches
     WHERE json_typeof(grounding_context -> 'reply_parent') = 'object'   -- jsonb_typeof if the column is jsonb
       AND state IN ('queued', 'generating', 'sending')
       AND content_approval_required = false                            -- omit before this migration has run
     GROUP BY 1, 2;                                                      -- expect zero rows

Legacy ``unknown`` replies (ambiguous SMTP outcome) are reported but do not block: nothing re-sends them. Operator
procedure -- pause LeadBoost reply traffic, drain the OLD workers, resolve or deliberately abandon each blocking row,
then run the gate until it passes, and only then start the new workers: migrations/README.md, "Legacy managed replies".
Nothing here migrates an old approval into a content approval, and nothing touches LeadBoost's action history.

Downgrade DROPS the three columns and the approval evidence. It REFUSES to run while any dispatch still
depends on the approval requirement -- state queued, generating, awaiting_approval or sending with the flag set --
because dropping the flag would turn a held/approved draft into an ordinary one, and a worker that is mid-generation
writes the column when it finishes. Resolve, cancel or let those finish first.

Run:        python migrations/013_external_dispatch_content_approval.py
Downgrade:  python migrations/013_external_dispatch_content_approval.py --downgrade
"""

import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from sqlalchemy import inspect, text

from mailer_agent.db import session_scope

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s: %(message)s")
logger = logging.getLogger(__name__)

TABLE = "external_dispatches"
COLUMNS = ("content_approval_required", "approved_content_sha256", "approved_at")
# States in which a row still depends on content_approval_required / approved_content_sha256:
#   queued             accepted (flag set at acceptance) or released (digest recorded)
#   generating         a worker is mid-LLM and will write the flag when it completes into the hold, and its
#                      completion UPDATE names the column -- dropping it underneath would break that write
#   awaiting_approval  held, awaiting release
#   sending            released and in flight (the SMTP worker verifies the digest from this row)
_DEPENDENT_STATES = ("queued", "generating", "awaiting_approval", "sending")


def _dialect(db) -> str:
    return db.get_bind().dialect.name


def _existing_columns(db) -> set:
    return {c["name"] for c in inspect(db.connection()).get_columns(TABLE)}


def _column_ddl(db) -> dict:
    pg = _dialect(db) == "postgresql"
    return {
        "content_approval_required": "BOOLEAN NOT NULL DEFAULT " + ("FALSE" if pg else "0"),
        "approved_content_sha256": "VARCHAR(64) NULL",
        "approved_at": ("TIMESTAMP WITH TIME ZONE NULL" if pg else "DATETIME NULL"),
    }


def add_columns(db) -> int:
    have = _existing_columns(db)
    ddl = _column_ddl(db)
    added = 0
    for name in COLUMNS:
        if name in have:
            logger.info("Column %s.%s already exists -- skipping", TABLE, name)
            continue
        db.execute(text(f"ALTER TABLE {TABLE} ADD COLUMN {name} {ddl[name]}"))
        logger.info("✓ Added %s.%s", TABLE, name)
        added += 1
    return added


def verify(db) -> bool:
    insp = inspect(db.connection())
    cols = {c["name"]: c for c in insp.get_columns(TABLE)}
    ok = True
    for name in COLUMNS:
        if name not in cols:
            logger.error("✗ %s.%s missing", TABLE, name)
            ok = False
    if not ok:
        return False
    if cols["content_approval_required"]["nullable"]:
        logger.error("✗ %s.content_approval_required must be NOT NULL", TABLE)
        ok = False
    nulls = db.execute(
        text(f"SELECT COUNT(*) FROM {TABLE} WHERE content_approval_required IS NULL")
    ).scalar()
    if nulls:
        logger.error("✗ %d row(s) have a NULL content_approval_required", nulls)
        ok = False
    if ok:
        logger.info("✓ %s content-approval columns present; content_approval_required is NOT NULL", TABLE)
    return ok


def run() -> bool:
    logger.info("Starting migration 013: external_dispatches content approval")
    with session_scope() as db:
        try:
            add_columns(db)
            db.commit()
            ok = verify(db)
            logger.info("✅ Migration 013 completed" if ok else "⚠️ Migration 013 verification failed")
            return ok
        except Exception:
            logger.exception("Migration 013 failed")
            db.rollback()
            raise


def downgrade() -> bool:
    logger.info("Starting migration 013 DOWNGRADE")
    with session_scope() as db:
        try:
            have = _existing_columns(db)
            if "content_approval_required" in have:
                placeholders = ", ".join(f"'{s}'" for s in _DEPENDENT_STATES)
                dependent = db.execute(
                    text(
                        f"SELECT COUNT(*) FROM {TABLE} "
                        f"WHERE content_approval_required = {'TRUE' if _dialect(db) == 'postgresql' else '1'} "
                        f"AND state IN ({placeholders})"
                    )
                ).scalar()
                if dependent:
                    logger.error(
                        "✗ REFUSING downgrade: %d managed-reply dispatch(es) still depend on the approval "
                        "requirement (awaiting_approval / released-and-unfinished). Dropping the flag would "
                        "turn them into ordinary sendable rows. Cancel or let them finish first.",
                        dependent,
                    )
                    return False
            for name in COLUMNS:
                if name in have:
                    logger.warning("Dropping %s.%s", TABLE, name)
                    db.execute(text(f"ALTER TABLE {TABLE} DROP COLUMN {name}"))
                    logger.info("✓ Dropped %s.%s", TABLE, name)
            db.commit()
            return True
        except Exception:
            logger.exception("Migration 013 downgrade failed")
            db.rollback()
            raise


if __name__ == "__main__":
    try:
        ok = downgrade() if "--downgrade" in sys.argv[1:] else run()
        sys.exit(0 if ok else 1)
    except Exception:
        logger.exception("Unhandled error during migration 013")
        sys.exit(1)
