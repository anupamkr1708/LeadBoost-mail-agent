"""
Managed-reply content approval -- the three LeadBoost-integration operations on a held reply draft.

    GET  /integrations/leadboost/reply-drafts/{idempotency_key}            read the exact draft
    POST /integrations/leadboost/reply-drafts/{idempotency_key}/release    approve-and-release, by digest
    POST /integrations/leadboost/reply-drafts/{idempotency_key}/cancel     revoke an unreleased draft

``idempotency_key`` is declared ``:path`` on all three routes so that a caller-supplied key containing "/"
(LeadBoost percent-encodes keys with ``quote(key, safe="")``; the server decodes ``%2F`` before routing) still
reaches its handler, exactly like the C9.3 conversation route. The key is only ever used as a bound parameter of
an equality predicate on (organization_id, idempotency_key).

The draft itself is created by the EXISTING POST .../outreach-requests (with ``in_reply_to``) and
generated by the EXISTING generation worker, which now finishes a managed reply into
ExternalDispatch.state = AWAITING_APPROVAL instead of QUEUED. Nothing here generates text, calls the LLM,
creates an ExternalDispatch or a Message, or sends mail: release only moves the SAME dispatch from the hold
into the existing sendable queue, and the existing SMTP worker does the sending (re-verifying the digest
immediately before SMTP).

Authorization model
-------------------
* Tenant: ``get_integration_org_id`` (fail-closed; never honours ALLOW_INSECURE_NO_AUTH). The organization is
  the one the presented X-API-Key maps to; nothing about it comes from the path or body. Every query filters
  on organization_id in the predicate. Another tenant's key, an unknown key, an ordinary (non-reply)
  dispatch and a missing row all produce the identical 404.
* Four kinds of operation are told apart by ONE tenant-scoped lookup (``_classify``), never by the approval flag
  alone, because the flag is ``false`` on every row that existed before migration 013:

      nonexistent            no row for (organization, key)                                  -> 404
      non-reply              row, flag false, no ``reply_parent`` in grounding_context       -> 404 (same body)
      LEGACY C9.4 reply      row, flag false, ``reply_parent`` object in grounding_context   -> never approvable
      NEW C9.5 reply         row, flag true                                                  -> the approval flow

  A legacy reply was accepted by code that sent it WITHOUT a reviewed digest, so it may be queued, sending, sent
  or in an ambiguous state. Answering 404 for it would tell LeadBoost "the Mailer has no such operation", which
  LeadBoost reads as permission to cancel locally while the message may be about to go out (or already did).
  So a legacy reply is NEVER a 404 and is NEVER written to by this module: read and release answer 409
  ``legacy_reply_requires_reconciliation``; cancel answers 200 only where the Mailer can prove nothing was or
  can be sent (``failed``: SendOutcome.FAILED / a failed generation, or ``cancelled`` by an operator), and the
  same 409 in every other state.
* This is NOT the native approval path. ``POST /messages/{id}/approve`` still refuses every
  integration-managed message in every state (tests/test_message_approval_external_dispatch_guard.py). The
  Message stays an integration-owned DRAFT throughout; it never becomes a native draft.
* LeadBoost's approval is the human authorization; this endpoint's contribution is proving that the text
  being released is byte-for-byte the text that approval was given for.

Release semantics (all in one place so the invariant is reviewable)
------------------------------------------------------------------
1. Resolve (organization, idempotency_key); require content_approval_required.
2. Require AWAITING_APPROVAL, a persisted outbound DRAFT message, and previewable size.
3. Recompute the digest from the CURRENT stored subject/body and compare with the caller's. Any difference,
   or a malformed digest (422 from the schema), changes nothing.
4. One atomic UPDATE ... WHERE state='awaiting_approval' AND message_id=<that message> records the digest and
   approval time and moves the row to QUEUED. Losing a race (cancel / a concurrent release) is re-read and
   classified: the same digest is an idempotent success, anything else is a 409.
Replaying a release with the digest already recorded is a 200 and changes nothing, in any later state.
"""

from __future__ import annotations

import logging

from fastapi import APIRouter, Depends, HTTPException, Path
from sqlalchemy.orm import Session

from mailer_agent.api.deps import get_integration_org_id
from mailer_agent.db import get_db
from mailer_agent.followup.work_claiming import cancel_unreleased_dispatch, release_held_dispatch
from mailer_agent.mail import content_digest
from mailer_agent.models import (
    ExternalDispatch,
    ExternalDispatchState as S,
    Message,
    MessageDirection,
    MessageStatus,
)
from mailer_agent.schemas import LeadBoostReplyDraftOut, LeadBoostReplyDraftReleaseIn

logger = logging.getLogger("mailer_agent.api.integrations_reply_drafts")

# No router-level require_api_key (it is open when no keys are configured); every route's own dependency,
# get_integration_org_id, authenticates and fails closed.
router = APIRouter(prefix="/integrations/leadboost", tags=["integrations"])

DRAFT_VERSION = 1  # content is immutable in v1 (no edit / regenerate); bump only with versioned re-approval

_KEY = Path(..., min_length=1, max_length=255)

_NOT_FOUND = "Reply draft not found"
_STATES = frozenset({"generating", "awaiting_approval", "queued", "sending", "sent", "failed", "unknown", "cancelled"})


def _not_found() -> HTTPException:
    return HTTPException(status_code=404, detail=_NOT_FOUND)


LEGACY_RECONCILIATION = "legacy_reply_requires_reconciliation"

# Legacy states in which the Mailer can PROVE nothing was sent and nothing can ever be sent for this operation.
# FAILED mirrors SendOutcome.FAILED ("definitely did not send") and a failed generation; nothing re-queues a FAILED
# row. CANCELLED is only ever written for a legacy row by a deliberate operator action (the rollout runbook).
# Everything else -- QUEUED (with or without a message), GENERATING, SENDING, SENT, UNKNOWN, and any state this
# code does not recognise -- may have sent, may be about to send, or cannot be shown not to have sent.
_LEGACY_PROVABLY_UNSENT = frozenset({S.FAILED.value, S.CANCELLED.value})


def _is_legacy_managed_reply(dispatch: ExternalDispatch) -> bool:
    """A reply accepted before approval-by-digest existed: the new flag is false, but the immutable
    ``grounding_context`` snapshot still carries the ``reply_parent`` object only a reply ever has."""
    ctx = dispatch.grounding_context
    return (
        dispatch.content_approval_required is not True
        and isinstance(ctx, dict)
        and isinstance(ctx.get("reply_parent"), dict)
    )


def _classify(db: Session, org_id: str, key: str) -> tuple[ExternalDispatch, bool]:
    """Tenant-scoped lookup; returns (row, is_legacy). Raises the 404 for a nonexistent operation and for an
    ordinary (non-reply) one -- the same body, so the two are indistinguishable. populate_existing so a re-read
    after a lost race sees the winner."""
    row = (
        db.query(ExternalDispatch)
        .populate_existing()
        .filter(
            ExternalDispatch.organization_id == org_id,
            ExternalDispatch.idempotency_key == key,
        )
        .first()
    )
    if row is None:
        raise _not_found()
    if row.content_approval_required is True:
        return row, False
    if _is_legacy_managed_reply(row):
        return row, True
    raise _not_found()  # an ordinary outreach dispatch is not a reply draft


def _legacy_conflict() -> HTTPException:
    return HTTPException(status_code=409, detail=LEGACY_RECONCILIATION)


def _load_dispatch(db: Session, org_id: str, key: str) -> ExternalDispatch:
    """Tenant-scoped lookup for the approval flow (read, release). A NEW reply is returned; a LEGACY reply is a
    409 (it exists, and it must never be approved or released through this flow); anything else is a 404."""
    row, legacy = _classify(db, org_id, key)
    if legacy:
        logger.warning(
            "legacy managed reply refused by the approval flow: org=%s dispatch=%s state=%s",
            org_id, row.public_reference, row.state,
        )
        raise _legacy_conflict()
    return row


def _load_message(db: Session, dispatch: ExternalDispatch) -> Message:
    """The dispatch's ONE outbound message, re-verified to belong to the dispatch's own contact."""
    msg = (
        db.query(Message)
        .populate_existing()
        .filter(
            Message.id == dispatch.message_id,
            Message.contact_id == dispatch.contact_id,
            Message.direction == MessageDirection.OUTBOUND.value,
        )
        .first()
    )
    if msg is None:
        logger.error("reply draft integrity failure: dispatch %s has no matching outbound message", dispatch.id)
        raise _not_found()
    return msg


def _draft_state(dispatch: ExternalDispatch) -> str:
    if dispatch.state == S.GENERATING.value or (
        dispatch.state == S.QUEUED.value and dispatch.message_id is None
    ):
        return "generating"
    if dispatch.state not in _STATES:
        logger.error("reply draft has unrecognised state %r (dispatch %s)", dispatch.state, dispatch.id)
        raise _not_found()
    return dispatch.state


def _view(db: Session, dispatch: ExternalDispatch) -> LeadBoostReplyDraftOut:
    state = _draft_state(dispatch)
    if dispatch.message_id is None:
        # generating / failed-before-a-draft / cancelled-before-a-draft: there is no content to show.
        return LeadBoostReplyDraftOut(state=state, updated_at=dispatch.updated_at)
    message = _load_message(db, dispatch)
    try:
        content_digest.enforce_preview_limits(message.subject, message.body)
        digest = content_digest.content_sha256(message.subject, message.body)
    except content_digest.DraftTooLarge:
        # Never show (or let anyone approve) a body that cannot be shown in full.
        raise HTTPException(status_code=422, detail="draft_too_large") from None
    except content_digest.DigestError:
        raise HTTPException(status_code=422, detail="draft_unverifiable") from None
    return LeadBoostReplyDraftOut(
        state=state,
        subject=message.subject if message.subject is not None else "",
        body=message.body,
        content_sha256=digest,
        draft_version=DRAFT_VERSION,
        updated_at=dispatch.updated_at,
    )


@router.get("/reply-drafts/{idempotency_key:path}", response_model=LeadBoostReplyDraftOut)
def read_reply_draft(
    idempotency_key: str = _KEY,
    org_id: str = Depends(get_integration_org_id),
    db: Session = Depends(get_db),
):
    """Strictly read-only: tenant-scoped SELECTs, then serialize. Never claims, recovers, generates,
    approves, releases or sends, and is safe to call repeatedly (and to poll)."""
    return _view(db, _load_dispatch(db, org_id, idempotency_key))


def _already_released(dispatch: ExternalDispatch, digest: str) -> bool:
    """True when this row has been released with exactly this digest (any later state)."""
    return dispatch.approved_content_sha256 is not None and content_digest.digests_equal(
        dispatch.approved_content_sha256, digest
    )


def _classify_unreleasable(dispatch: ExternalDispatch, digest: str) -> LeadBoostReplyDraftOut | None:
    """For a row that is NOT currently AWAITING_APPROVAL: None means 'idempotent success, same digest';
    otherwise raises the right 409."""
    state = _draft_state(dispatch)
    if dispatch.approved_content_sha256 is not None:
        if _already_released(dispatch, digest):
            return None
        raise HTTPException(status_code=409, detail="draft_already_released_with_different_content")
    if state == "cancelled":
        raise HTTPException(status_code=409, detail="draft_cancelled")
    if state == "generating":
        raise HTTPException(status_code=409, detail="draft_not_ready")
    if state == "failed":
        raise HTTPException(status_code=409, detail="draft_generation_failed")
    raise HTTPException(status_code=409, detail="draft_not_releasable")


@router.post("/reply-drafts/{idempotency_key:path}/release", response_model=LeadBoostReplyDraftOut)
def release_reply_draft(
    payload: LeadBoostReplyDraftReleaseIn,
    idempotency_key: str = _KEY,
    org_id: str = Depends(get_integration_org_id),
    db: Session = Depends(get_db),
):
    """Authorize the exact held draft for sending. Does not send, generate or create anything."""
    dispatch = _load_dispatch(db, org_id, idempotency_key)

    if dispatch.state == S.AWAITING_APPROVAL.value:
        if dispatch.message_id is None:
            raise HTTPException(status_code=409, detail="draft_not_ready")
        message = _load_message(db, dispatch)
        if message.status != MessageStatus.DRAFT.value:
            raise HTTPException(status_code=409, detail="draft_not_releasable")
        try:
            content_digest.enforce_preview_limits(message.subject, message.body)
            current = content_digest.content_sha256(message.subject, message.body)
        except content_digest.DraftTooLarge:
            raise HTTPException(status_code=422, detail="draft_too_large") from None
        except content_digest.DigestError:
            raise HTTPException(status_code=422, detail="draft_unverifiable") from None

        if not content_digest.digests_equal(current, payload.content_sha256):
            # Stale or modified content: nothing is written. LeadBoost must re-read and re-approve.
            logger.warning(
                "reply draft release refused: digest mismatch org=%s dispatch=%s", org_id, dispatch.public_reference
            )
            raise HTTPException(status_code=409, detail="draft_changed")

        won = release_held_dispatch(
            db,
            organization_id=org_id,
            dispatch_id=dispatch.id,
            message_id=message.id,
            content_sha256=current,
        )
        if won:
            db.commit()
            logger.info(
                "reply draft released: org=%s dispatch=%s (AWAITING_APPROVAL -> QUEUED)",
                org_id, dispatch.public_reference,
            )
            return _view(db, _load_dispatch(db, org_id, idempotency_key))
        # Lost the race (cancel, or a concurrent identical release): re-read and classify.
        db.rollback()
        dispatch = _load_dispatch(db, org_id, idempotency_key)
        if dispatch.state == S.AWAITING_APPROVAL.value:
            raise HTTPException(status_code=409, detail="draft_not_releasable")

    if _classify_unreleasable(dispatch, payload.content_sha256) is None:
        return _view(db, dispatch)  # idempotent replay: the same approved digest, nothing changed
    raise HTTPException(status_code=409, detail="draft_not_releasable")  # pragma: no cover (classifier raises)


def _cancel_legacy(dispatch: ExternalDispatch) -> LeadBoostReplyDraftOut:
    """A legacy (C9.4) reply is never written to here. 200 only when the row PROVES nothing was or can be sent
    (failed / cancelled); every other state is a 409 so LeadBoost cannot mark its action cancelled while the
    Mailer may send or may have sent. No content is returned: a legacy row has no reviewed draft."""
    if dispatch.state in _LEGACY_PROVABLY_UNSENT:
        return LeadBoostReplyDraftOut(state=dispatch.state, updated_at=dispatch.updated_at)
    logger.warning(
        "legacy managed reply cancel refused: org=%s dispatch=%s state=%s (needs operator reconciliation)",
        dispatch.organization_id, dispatch.public_reference, dispatch.state,
    )
    raise _legacy_conflict()


@router.post("/reply-drafts/{idempotency_key:path}/cancel", response_model=LeadBoostReplyDraftOut)
def cancel_reply_draft(
    idempotency_key: str = _KEY,
    org_id: str = Depends(get_integration_org_id),
    db: Session = Depends(get_db),
):
    """Revoke an UNRELEASED draft so it can never be sent. Idempotent. Once released it is a 409: a
    released message belongs to the send worker and LeadBoost does not offer cancel past that point.

    A LEGACY (C9.4) reply is neither a 404 nor ever modified: see ``_cancel_legacy``."""
    dispatch, legacy = _classify(db, org_id, idempotency_key)
    if legacy:
        return _cancel_legacy(dispatch)
    if dispatch.state == S.CANCELLED.value:
        return _view(db, dispatch)

    if cancel_unreleased_dispatch(db, organization_id=org_id, dispatch_id=dispatch.id):
        db.commit()
        logger.info("reply draft cancelled: org=%s dispatch=%s", org_id, dispatch.public_reference)
        return _view(db, _load_dispatch(db, org_id, idempotency_key))

    db.rollback()
    dispatch = _load_dispatch(db, org_id, idempotency_key)
    if dispatch.state == S.CANCELLED.value:
        return _view(db, dispatch)  # a concurrent cancel won: same outcome
    raise HTTPException(status_code=409, detail="draft_already_released")
